class HelpPage(QWidget):
    def __init__(self, parent=None):
        super().__init__(parent)
        root = QVBoxLayout(self)
        root.setContentsMargins(0, 0, 0, 0)
        title = QLabel('Помощь — как пользоваться программой')
        title.setObjectName('sectionTitle')
        root.addWidget(title)
        body = QHBoxLayout()
        root.addLayout(body, 1)
        self.topics = QListWidget()
        self.topics.setObjectName('helpTopics')
        self.topics.setMaximumWidth(245)
        self.pages = QStackedWidget()
        for caption, html in HELP:
            self.topics.addItem(caption)
            page = QTextBrowser()
            page.setOpenExternalLinks(True)
            page.setObjectName('helpText')
            page.setHtml('<style>body{font-family:"Segoe UI",sans-serif;font-size:14px;color:#dce6f2;line-height:1.55;} h2{color:#f5f8fc;font-size:23px;}h3{color:#86d8c5;margin-top:23px;} p,li{line-height:1.6;}a{color:#72d2bd;}pre{white-space:pre-wrap;font-size:12px;}</style>' + html)
            self.pages.addWidget(page)
        self.topics.currentRowChanged.connect(self.pages.setCurrentIndex)
        body.addWidget(self.topics)
        body.addWidget(self.pages, 1)
        self.topics.setCurrentRow(0)
